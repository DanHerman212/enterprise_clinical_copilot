"""The chips and driver questions each holdout record offers — zero LLM calls.

Mirrors `evaluation/inventory/dev_followup_matrix.py` for `dev_suite.HOLDOUT_HADM_IDS`
and writes `evaluation/holdout_followup_matrix.md`.

    ./.venv/bin/python evaluation/inventory/holdout_followup_matrix.py
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from services.agent.postprocess import followups  # noqa: E402
from services.agent.routing import routing  # noqa: E402

from evaluation.inventory.dev_followup_matrix import (  # noqa: E402
    ANSWER,
    COMMANDS,
    ROW,
    _cells,
    _drivers,
)
from evaluation.outpatient_oracle import OUTPATIENT_HADM_IDS  # noqa: E402
from evaluation.platform import dev_suite  # noqa: E402

OUT = REPO / "evaluation" / "holdout_followup_matrix.md"

HOLDOUT = tuple(int(hadm) for hadm in dev_suite.HOLDOUT_HADM_IDS)

ARCHETYPE = {
    90000087: "dedicated brief meds (IV Flagyl/Levaquin), above threshold",
    90000067: "complex meds, prednisone taper, above threshold",
    90000101: "oncology (Ewing sarcoma), no dedicated meds, abnormal labs",
    90000050: "below threshold, no dedicated meds (traumatic contusion)",
    90000026: "direct emergency, single discharge_summary section, above threshold",
    90000028: "outpatient encounter (speech therapy)",
    90000077: "critical haemoglobin, Coumadin in discharge instructions, above threshold",
    90000088: "critical haemoglobin, oncology/ESRD, no dedicated meds, above threshold",
    90000104: "critical haemoglobin, dedicated meds, above threshold",
    90000102: "urgent medical admission, no dedicated meds, high risk",
}


async def main() -> int:
    """Compute follow-up chips and ranked driver questions across all 10 holdout records."""
    problems: list[str] = []
    short: list[str] = []
    blocks: list[str] = []

    for hadm_id in HOLDOUT:
        outpatient = hadm_id in OUTPATIENT_HADM_IDS
        lines = [f"## {hadm_id} — {ARCHETYPE[hadm_id]}", ""]
        if outpatient:
            lines += [
                "Outpatient encounter: the chart has no admission and no risk "
                "estimate, so no driver bar and no driver question.",
                "",
            ]
        lines += [
            "| command | " + " | ".join(f"`[{i}]`" for i in range(ROW)) + " | chips |",
            "|---" * (ROW + 2) + "|",
        ]
        for question, builder in COMMANDS:
            state = await builder(hadm_id)
            chips = followups.suggest(
                question,
                ANSWER,
                scope="patient_chart",
                state=state,
                outpatient=outpatient,
            )
            lines.append(
                f"| `{question}` | " + " | ".join(_cells(chips, ROW)) + f" | {len(chips)} |"
            )
            if len(chips) < ROW:
                short.append(f"{hadm_id} {question} → {len(chips)}")
            for chip in chips:
                if routing.asks_for_literature(chip):
                    problems.append(f"{hadm_id} {question}: literature cue: {chip}")
                if len(chip) > followups._MAX_QUESTION_CHARS:
                    problems.append(f"{hadm_id} {question}: over cap: {chip}")
        lines.append("")
        if not outpatient:
            ranked = await _drivers(hadm_id)
            lines += [
                "| # | feature | label | direction | chip (exact) |",
                "|---|---|---|---|---|",
            ]
            for index, (feature, label, direction, chip) in enumerate(ranked, start=1):
                lines.append(
                    f"| {index} | `{feature}` | {label} | {direction} "
                    f"| {chip.replace('|', chr(92) + '|')} |"
                )
            lines.append("")
        blocks.append("\n".join(lines))

    header = [
        "# Holdout UI Affordances — Phase 05",
        "",
        "Generated by `evaluation/inventory/holdout_followup_matrix.py`: the deterministic "
        "follow-up selector and the driver-bar question template, run over the "
        f"{len(HOLDOUT)} holdout records against the same tool payloads the commands retrieve. "
        "**Zero LLM calls.**",
        "",
        f"The row holds up to {ROW} chips; `—` marks a slot the selector left empty. "
        "`/meds` runs without the model's extracted medication rows (the matrix cannot "
        "produce them without an LLM call), so a regimen chip may name a different pair "
        "of drugs live.",
        "",
        "Driver questions are the exact string a driver bar sends, produced by "
        "`driver_question(humanize(feature))`. A `risk_driver` turn copies one of them "
        "rather than rebuilding it.",
        "",
    ]
    if short:
        header += [f"## Command/record pairs offering fewer than {ROW} chips", ""]
        header += [f"- {item}" for item in short]
        header += [""]
    if problems:
        header += ["## Violations", ""] + [f"- {item}" for item in problems] + [""]

    OUT.write_text(
        "\n".join(header) + "\n" + "\n".join(blocks) + "\n", encoding="utf-8"
    )
    print(f"wrote {OUT.relative_to(REPO)} ({len(HOLDOUT)} records, 0 LLM calls)")
    print(f"{len(short)} command/record pair(s) offered fewer than {ROW} chips")
    if problems:
        print("VIOLATIONS")
        for line in problems:
            print(" ", line)
        return 1
    print("no chip carried a literature cue; every chip is within the row cap")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
