#!/usr/bin/env bash
# Copy the eval case fixtures to the bucket the eval jobs mount.
#
#   scripts/sync_fixtures.sh
#
# Why this exists: the jobs read case files from gs://ecc-eval-artifacts/fixtures/
# (mounted at /mnt/gcs, selected by EVAL_CASES_DIR), so a fixture edit is a copy
# instead of a fifteen-minute image build. That only helps if the copy is deliberate —
# a run silently reading a stale object reports a pass rate for a suite nobody is
# maintaining. git stays the source of truth; this publishes it.
#
# Falls back to the image's baked copies when the prefix is empty, so a missing upload
# is a warning rather than a broken run.
set -euo pipefail

BUCKET="${BUCKET:-gs://ecc-eval-artifacts/fixtures}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

FILES=(
  evaluation/agent/suite2_cases.json
  evaluation/agent/adversarial_cases.json
  evaluation/agent/results/cases_82.json
)

for f in "${FILES[@]}"; do
  if [[ ! -f "$f" ]]; then
    # cases_82.json is generated by build_census.py, so it may legitimately be absent
    # in a fresh checkout. Say so instead of uploading nothing quietly.
    echo "skip: $f (not present — run build_census.py first?)" >&2
    continue
  fi
  echo "uploading $f -> $BUCKET/$(basename "$f")"
  gcloud storage cp "$f" "$BUCKET/$(basename "$f")"
done

echo "done. verify with: gcloud storage ls $BUCKET/"
